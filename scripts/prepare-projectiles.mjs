/** Bake the selected OBJ visuals into synchronous, shareable Babylon vertex data. */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const selection = { missile: ['rocket', 1.8], mortar: ['mortar', 1.25], nuke: ['nook', 3] };
const prepared = {};
const report = [];
for (const [kind, [name, length]] of Object.entries(selection)) {
    const source = await readFile(`new-assets/models/${name}.obj`, 'utf8');
    const positions = [], normals = [], uvs = [], faces = [];
    for (const line of source.split(/\r?\n/)) {
        const [tag, ...parts] = line.trim().split(/\s+/);
        if (tag === 'v') positions.push(parts.map(Number));
        if (tag === 'vn') normals.push(parts.map(Number));
        if (tag === 'vt') uvs.push(parts.map(Number));
        if (tag === 'f') faces.push(parts);
    }
    const min = [0, 1, 2].map(axis => Math.min(...positions.map(p => p[axis])));
    const max = [0, 1, 2].map(axis => Math.max(...positions.map(p => p[axis])));
    const center = min.map((value, axis) => (value + max[axis]) / 2);
    const scale = length / (max[2] - min[2]);
    const data = { positions: [], normals: [], uvs: [], indices: [] };
    const vertices = new Map();
    const round = value => Math.round(value * 1e6) / 1e6;
    for (const face of faces) {
        const indices = face.map(token => {
            if (vertices.has(token)) return vertices.get(token);
            const [pi, ti, ni] = token.split('/').map(Number);
            if (!positions[pi - 1] || !normals[ni - 1] || !uvs[ti - 1]) throw new Error(`Incomplete vertex: ${name}: ${token}`);
            const index = data.positions.length / 3;
            data.positions.push(...positions[pi - 1].map((v, axis) => round((v - center[axis]) * scale)));
            data.normals.push(...normals[ni - 1].map(round));
            data.uvs.push(...uvs[ti - 1].slice(0, 2).map(round));
            vertices.set(token, index);
            return index;
        });
        // OBJ is counterclockwise; Babylon's default left-handed front face is clockwise.
        for (let i = 1; i < indices.length - 1; i++) data.indices.push(indices[0], indices[i + 1], indices[i]);
    }
    prepared[kind] = data;
    report.push({ kind, source: `new-assets/models/${name}.obj`, sha256: createHash('sha256').update(source).digest('hex'), vertices: data.positions.length / 3, triangles: data.indices.length / 3, length, dimensions: max.map((v, axis) => round((v - min[axis]) * scale)), forward: '+Z' });
}
await mkdir('src/assets/models/prepared', { recursive: true });
await writeFile('src/assets/models/prepared/ProjectileGeometry.ts', '/** Generated by scripts/prepare-projectiles.mjs; do not hand-edit. */\nexport const PROJECTILE_GEOMETRY = ' + JSON.stringify(prepared) + ';\n');
await writeFile('docs/assets/prepared-projectiles.json', JSON.stringify(report, null, 2) + '\n');
console.log(report);
